#!/usr/bin/env python3
"""Read CDC line coding during serial bootloader traffic; check retries and SRAM."""
import argparse
from collections import deque
from pathlib import Path
import shutil

from active_usb_setup import UsbStackGuard
from recovery_replay import MODE, PROJECT, RecoveryBench, period, reply


def line_coding(bench, baud, write=False):
    usb = bench.usb
    start = len(usb.control_in)
    data = baud.to_bytes(4, 'little') + bytes((0, 0, 8))
    endpoint = usb.endpoints[0]
    assert endpoint.enabled and not endpoint.setup
    endpoint.data = deque((0x21, 0x20, 0, 0, 0, 0, 7, 0) if write else
                          (0xa1, 0x21, 0, 0, 0, 0, 7, 0))
    endpoint.setup = endpoint.txini = True
    endpoint.rxouti = False
    usb.control_payload = deque(data) if write else None
    usb.control_response_bytes = None if write else len(data)
    # The AVR's interrupt masks and foreground loop decide dispatch.
    bench.run(3)
    assert usb.control_in[start:] == ([b''] if write else [data]), 'CDC line coding mismatch'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--images', type=Path, default=PROJECT / 'build')
    parser.add_argument('--objdump', default=shutil.which('avr-objdump') or
                        Path.home() / '.platformio/packages/toolchain-atmelavr/bin/avr-objdump')
    args = parser.parse_args()
    bench = RecoveryBench(args.images, args.images, args.objdump)
    guard = UsbStackGuard(bench.usb)
    bench.serial_wire.clear()
    bench.serial_in.clear()
    line_coding(bench, 57600, write=True)
    line_coding(bench, 57600)
    line_coding(bench, 115200, write=True)
    # First sign-on gets no response; the uploader retries over the same CDC pair.
    sign_on = reply(1, b'\x01')
    bench.usb.host_out.append(sign_on)
    bench.run(25)
    bench.usb.host_out.append(sign_on)
    bench.run(12)
    expected_wire = bytearray(sign_on * 2)
    assert bench.serial_wire == expected_wire
    sign_on_reply = reply(1, b'\x01\x00\x08AVRISP_2')
    bench.replies(sign_on_reply)
    expected_in = bytearray(sign_on_reply)
    assert bench.serial_in == expected_in
    # Ordinary readback responses are generated by the mock bootloader.
    # Query the active serial settings while those bytes arrive at 115200.
    for seq in range(2, 6):
        request = reply(seq, bytes((0x14, 0, 128, 0x20)))
        response = reply(seq, bytes((0x14, 0)) + bytes(range(128)) + b'\0')
        bench.usb.host_out.append(request)
        expected_wire.extend(request)
        bench.run(6)
        assert bench.serial_wire == expected_wire
        start = bench.usb.cycles
        byte_period = period(bench.usb, 0xc8)
        bench.usb.input.extend((start + index * byte_period, byte)
                               for index, byte in enumerate(response, 1))
        bench.run(3)
        # A serial application may reapply its existing settings. Reapply
        # the same rate on alternating reads; other reads only query it.
        line_coding(bench, 115200, write=seq % 2 == 0)
        bench.run(22)
        expected_in.extend(response)
        assert bench.serial_in == expected_in, 'CDC readback mismatch after setup'
    assert not bench.usb.overruns and bench.usb.mem[MODE] == 3
    print(f'CDC sign-on retry and four readbacks: {len(expected_wire)} serial TX, '
          f'{len(expected_in)} RX bytes exact, configured SET/GET line coding, '
          f'minimum 16U2 stack-to-static gap {guard.gap} bytes')


if __name__ == '__main__':
    main()
